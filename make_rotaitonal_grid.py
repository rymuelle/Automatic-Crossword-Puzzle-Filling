def enforce_rotational_symmetry(grid):
    rows = len(grid)
    cols = len(grid[0])

    # make a deep copy so we don't mutate input
    new_grid = [row[:] for row in grid]

    for r in range(rows):
        for c in range(cols):
            if grid[r][c] == '.':
                sr = rows - 1 - r
                sc = cols - 1 - c
                new_grid[sr][sc] = '.'

    return new_grid


def draw_crossword(grid):
    rows = len(grid)
    cols = len(grid[0])

    horizontal = "───"
    top = "┌" + "┬".join([horizontal] * cols) + "┐"
    mid = "├" + "┼".join([horizontal] * cols) + "┤"
    bottom = "└" + "┴".join([horizontal] * cols) + "┘"

    print(top)
    for r, row in enumerate(grid):
        line = "│"
        for cell in row:
            if cell == '.':
                line += "███│"
            elif cell != ' ':
                line += "  {}│".format(cell)
            else:
                line += "   │"
        print(line)
        if r < rows - 1:
            print(mid)
    print(bottom)

